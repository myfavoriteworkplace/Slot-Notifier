import assert from "node:assert/strict";
import test from "node:test";
import { validateImageBytes } from "./signedUrl.service";

test("image verification checks file signatures and dimensions", () => {
  const png = new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x20,
  ]);
  assert.deepEqual(validateImageBytes(png, "image/png"), { width: 64, height: 32 });

  const jpeg = new Uint8Array([
    0xff, 0xd8, 0xff, 0xc0, 0x00, 0x0b, 0x08,
    0x00, 0x10, 0x00, 0x20, 0x01, 0x01, 0x11, 0x00,
    0xff, 0xd9,
  ]);
  assert.deepEqual(validateImageBytes(jpeg, "image/jpeg"), { width: 32, height: 16 });

  const webp = new Uint8Array([
    0x52, 0x49, 0x46, 0x46, 0x16, 0x00, 0x00, 0x00,
    0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x58,
    0x0a, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x4f, 0x00, 0x00, 0x27, 0x00, 0x00,
  ]);
  assert.deepEqual(validateImageBytes(webp, "image/webp"), { width: 80, height: 40 });
});

test("image verification rejects disguised and oversized images", () => {
  const png = new Uint8Array([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
    0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x20,
  ]);
  assert.throws(() => validateImageBytes(png, "image/jpeg"), /does not match/);

  const hugePng = new Uint8Array(png);
  hugePng[19] = 0x40;
  hugePng[20] = 0x00;
  hugePng[21] = 0x00;
  hugePng[22] = 0x40;
  hugePng[23] = 0x00;
  assert.throws(() => validateImageBytes(hugePng, "image/png"), /dimensions exceed/);
});